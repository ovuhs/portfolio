  function rid(n) {
    var s = '';
    while (s.length < n) s += Math.random().toString(36).slice(2);
    return s.slice(0, n);
  }
  function p2(n) { return String(n).padStart(2, '0'); }
  function dayKey(ms) { var d = new Date(ms); return d.getFullYear() + '-' + p2(d.getMonth() + 1) + '-' + p2(d.getDate()); }
  function startOfDay(ms) { var d = new Date(ms); d.setHours(0, 0, 0, 0); return d.getTime(); }

  function cfg() {
    var c = window.PORTFOLIO_CONFIG || {};
    return { url: (c.supabaseUrl || '').replace(/\/$/, ''), anon: c.supabaseAnonKey || '' };
  }

  /* ---------- identity & session ---------- */

  function getVid() {
    try {
      var vid = localStorage.getItem(VID_KEY);
      if (!vid) { vid = 'v-' + rid(10); localStorage.setItem(VID_KEY, vid); }
      return vid;
    } catch (e) {
      if (!getVid.mem) getVid.mem = 'v-' + rid(10);
      return getVid.mem;
    }
  }

  // Session lives in localStorage so several tabs count as one visit.
  var memSess = null;
  function touchSession(now) {
    var s = null;
    try { s = JSON.parse(localStorage.getItem(SESS_KEY) || 'null'); } catch (e) {}
    if (!s) s = memSess;
    var isNew = false;
    if (!s || !s.id || now - s.last > SESS_TIMEOUT_MS) { s = { id: 's-' + rid(10), last: now }; isNew = true; }
    else s.last = now;
    memSess = s;
    try { localStorage.setItem(SESS_KEY, JSON.stringify(s)); } catch (e) {}
    return { id: s.id, isNew: isNew };
  }

  function shouldTrack() {
    try {
      if (localStorage.getItem(FORCE_KEY) !== '1') {
        var h = location.hostname;
        if (h === 'localhost' || h === '127.0.0.1' || h === '[::1]' || h === '::1' || /\.localhost$/.test(h)) return false;
      }
      if (navigator.webdriver) return false;
      if (/bot|crawl|spider|slurp|headless|lighthouse|pagespeed|facebookexternalhit|embedly|whatsapp|telegrambot|uptime|monitor/i.test(navigator.userAgent || '')) return false;
      if (localStorage.getItem(OPT_KEY) === '1') return false;
    } catch (e) {}
    return true;
  }

  function getClientMeta() {
    var ua = navigator.userAgent || '';
    var browser = 'Other';
    if (/Edg\//i.test(ua)) browser = 'Edge';
    else if (/OPR\/|Opera/i.test(ua)) browser = 'Opera';
    else if (/SamsungBrowser/i.test(ua)) browser = 'Samsung';
    else if (/Firefox\//i.test(ua)) browser = 'Firefox';
    else if (/Chrome\//i.test(ua) || /CriOS/i.test(ua)) browser = 'Chrome';
    else if (/Safari\//i.test(ua)) browser = 'Safari';

    var os = 'Other';
    if (/Windows/i.test(ua)) os = 'Windows';
    else if (/Android/i.test(ua)) os = 'Android';
    else if (/iPhone|iPad|iPod/i.test(ua)) os = 'iOS';
    else if (/Macintosh|Mac OS X/i.test(ua)) os = (navigator.maxTouchPoints > 1) ? 'iOS' : 'macOS';
    else if (/CrOS/i.test(ua)) os = 'ChromeOS';
    else if (/Linux/i.test(ua)) os = 'Linux';

    var device = 'Desktop';
    if (/iPad|Tablet/i.test(ua) || (/Macintosh/i.test(ua) && navigator.maxTouchPoints > 1)) device = 'Tablet';
    else if (/Mobile|Android|iPhone|iPod/i.test(ua)) device = 'Mobile';
    else if (window.innerWidth < 768) device = 'Mobile';

    var ref = 'Direct';
    try {
      var q = new URLSearchParams(location.search);
      var u = q.get('utm_source') || q.get('ref') || q.get('source');
      if (u) ref = String(u).slice(0, 40);
    } catch (e) {}
    if (ref === 'Direct' && document.referrer) {
      try {
        var rUrl = new URL(document.referrer);
        if (rUrl.hostname !== location.hostname) ref = rUrl.hostname.replace(/^www\./, '');
      } catch (e) { ref = document.referrer.slice(0, 32); }
    }

    var screenRes = (window.screen && window.screen.width) ? (window.screen.width + 'x' + window.screen.height) : 'Unknown';
    var tz = 'Unknown';
    try { tz = Intl.DateTimeFormat().resolvedOptions().timeZone || 'Unknown'; } catch (e) {}
    var lang = (navigator.language || '').slice(0, 12);

    return { browser: browser, os: os, device: device, referrer: ref, screenRes: screenRes, tz: tz, lang: lang };
  }

  /* ---------- local store (this browser only) ---------- */

  function getLocalActivities() {
    try {
      var parsed = JSON.parse(localStorage.getItem(STORAGE_KEY) || 'null');
      if (parsed && Array.isArray(parsed.activities)) return parsed.activities;
    } catch (e) {}
    return [];
  }
  function saveLocalActivities(list) {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify({ v: 2, activities: list.slice(0, MAX_LOCAL) }));
      window.dispatchEvent(new CustomEvent('portfolio-analytics-update'));
    } catch (e) {}
  }

  /* ---------- sending ---------- */

  function postRow(c, body) {
    return fetch(c.url + '/rest/v1/site_activities', {
      method: 'POST',
      headers: { 'apikey': c.anon, 'Authorization': 'Bearer ' + c.anon, 'Content-Type': 'application/json', 'Prefer': 'return=minimal' },
      body: JSON.stringify(body),
      keepalive: true
    });
  }

  // Returns a promise of { ok, status, text } so callers can report problems.
  function syncToSupabase(payload) {
    var c = cfg();
    if (!c.url || !c.anon) return Promise.resolve({ ok: false, status: 0, text: 'not configured' });
    return postRow(c, payload).then(function(r) {
      if (r.ok) return { ok: true, status: r.status, text: '' };
      return r.text().then(function(t) {
        // Older tables lack the newer columns: retry without them rather than lose the visit.
        if (r.status === 400 && /PGRST204|column/i.test(t)) {
          var slim = {};
          Object.keys(payload).forEach(function(k) { if (k !== 'session_id' && k !== 'language') slim[k] = payload[k]; });
          return postRow(c, slim).then(function(r2) { return { ok: r2.ok, status: r2.status, text: '' }; });
        }
        return { ok: false, status: r.status, text: t };
      });
    }).catch(function(e) { return { ok: false, status: 0, text: String(e && e.message || e) }; });
  }

  var activeMs = 0, lastTick = document.hidden ? 0 : Date.now(), lastSent = 0, started = false;

  function recordActivity(type, detail, meta) {
    meta = meta || {};
    if (!shouldTrack()) return null;
    var now = Date.now();
    var sess = touchSession(now);
    var vid = getVid();
    var client = getClientMeta();
    var pageName = meta.page || (location.pathname || '/').replace(/^\/+|\/+$/g, '') || (location.hash ? location.hash.replace(/^#/, '') : 'intro') || 'intro';
    if (type === 'page_view') {
      started = true;
      var lp = recordActivity.lastPV;   // ignore an identical page view repeated within 3 seconds
      if (lp && lp.page === pageName && now - lp.time < 3000) return null;
      recordActivity.lastPV = { page: pageName, time: now };
    }

    var item = {
      id: 'act_' + now + '_' + rid(4),
      time: now, vid: vid, sid: sess.id, type: type, detail: detail || '', page: pageName,
      device: client.device, browser: client.browser, os: client.os, screen: client.screenRes,
      referrer: client.referrer, tz: client.tz, lang: client.lang
    };
    var list = getLocalActivities();
    list.unshift(item);
    saveLocalActivities(list);

    syncToSupabase({
      visitor_id: vid, session_id: sess.id, event_type: type, detail: detail || '', page: pageName,
      device: client.device, browser: client.browser, os: client.os, screen: client.screenRes,
      referrer: client.referrer, timezone: client.tz, language: client.lang
    });
    return item;
  }

  // Time on site: counts only the time the tab is visible, reported when the visitor leaves or switches tab.
  function sendTime() {
    if (lastTick) { activeMs += Date.now() - lastTick; lastTick = 0; }
    var s = Math.round(activeMs / 1000);
    if (started && s >= 3 && s !== lastSent) { lastSent = s; recordActivity('time_on_site', String(s)); }
  }
  try {
    document.addEventListener('visibilitychange', function() {
      if (document.hidden) sendTime(); else lastTick = Date.now();
    });
    window.addEventListener('pagehide', sendTime);
  } catch (e) {}

