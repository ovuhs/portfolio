  function buildSessions(evsAsc) {
    var map = {}, lastByVid = {}, counters = {}, list = [];
    evsAsc.forEach(function(e) {
      var key;
      if (e.sid) key = 's:' + e.sid;
      else {
        var l = lastByVid[e.vid];
        if (l === undefined || e.time - l > SESS_TIMEOUT_MS) counters[e.vid] = (counters[e.vid] || 0) + 1;
        lastByVid[e.vid] = e.time;
        key = 'v:' + e.vid + ':' + counters[e.vid];
      }
      var s = map[key];
      if (!s) {
        s = map[key] = { id: key, vid: e.vid, start: e.time, end: e.time, pv: 0, act: 0, secs: 0,
          device: e.device, browser: e.browser, os: e.os, ref: e.referrer, tz: e.tz, lang: e.lang, screen: e.screen };
        list.push(s);
      }
      if (e.time > s.end) s.end = e.time;
      if (e.type === 'time_on_site') { var n = parseInt(e.detail, 10); if (n > s.secs) s.secs = n; }
      else if (e.type === 'page_view') s.pv++;
      else if (e.type !== 'theme_toggle') s.act++;
    });
    return list;
  }
  function durOf(s) { return Math.max(s.secs, (s.end - s.start) / 1000); }

  function kpis(sessions, evs, startMs, endMs, firstSeen) {
    var inS = sessions.filter(function(s) { return s.start >= startMs && s.start < endMs; });
    var vis = {};
    inS.forEach(function(s) { vis[s.vid] = (vis[s.vid] || 0) + 1; });
    var ids = Object.keys(vis);
    var returning = ids.filter(function(v) { return vis[v] > 1 || firstSeen[v] < startMs; }).length;
    var pv = 0;
    evs.forEach(function(e) { if (e.type === 'page_view' && e.time >= startMs && e.time < endMs) pv++; });
    var durs = inS.map(durOf).filter(function(x) { return x > 0; });
    var avg = durs.length ? durs.reduce(function(a, b) { return a + b; }, 0) / durs.length : 0;
    var bounces = inS.filter(function(s) { return s.pv <= 1 && s.act === 0 && durOf(s) < 15; }).length;
    return {
      visits: inS.length, visitors: ids.length, pageViews: pv, avgSecs: avg,
      bounceRate: inS.length ? bounces / inS.length * 100 : 0,
      returningRate: ids.length ? returning / ids.length * 100 : 0,
      pagesPerVisit: inS.length ? pv / inS.length : 0
    };
  }

  function tally(map, key) { map[key] = (map[key] || 0) + 1; }
  function toList(map, limit) {
    var arr = Object.keys(map).map(function(k) { return { name: k, count: map[k] }; }).sort(function(a, b) { return b.count - a.count; });
    return limit ? arr.slice(0, limit) : arr;
  }

  // days: 1 = today, 7, 30, or 0 = all time.
  function summarize(events, opts) {
    opts = opts || {};
    var days = opts.days === undefined ? 30 : opts.days;
    var now = Date.now();
    var evs = (events || []).filter(function(e) { return e && e.type !== 'test'; }).slice().sort(function(a, b) { return a.time - b.time; });
    var sessions = buildSessions(evs);

    var firstSeen = {};
    sessions.forEach(function(s) { if (firstSeen[s.vid] === undefined || s.start < firstSeen[s.vid]) firstSeen[s.vid] = s.start; });

    var todayStart = startOfDay(now);
    var start = days === 0 ? 0 : (days === 1 ? todayStart : todayStart - (days - 1) * DAY);
    var end = now + 1;
    var cur = kpis(sessions, evs, start, end, firstSeen);
    var prev = null;
    if (days > 0) {
      var span = end - start;
      prev = kpis(sessions, evs, start - span, start, firstSeen);
    }

    var inS = sessions.filter(function(s) { return s.start >= start && s.start < end; });
    var inE = evs.filter(function(e) { return e.time >= start && e.time < end; });

    // Trend buckets
    var series = [], keyFn;
    if (days === 1) {
      for (var h = 0; h < 24; h++) series.push({ key: h, label: p2(h) + ':00', visits: 0, vset: {} });
      keyFn = function(s) { return new Date(s.start).getHours(); };
    } else {
      var n = days === 0 ? 0 : days;
      if (days === 0) {
        var first = sessions.length ? startOfDay(sessions[0].start) : todayStart;
        n = Math.min(90, Math.round((todayStart - first) / DAY) + 1);
      }
      var mon = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
      for (var i = n - 1; i >= 0; i--) {
        var d = new Date(todayStart - i * DAY);
        series.push({ key: dayKey(d.getTime()), label: mon[d.getMonth()] + ' ' + d.getDate(), visits: 0, vset: {} });
      }
      keyFn = function(s) { return dayKey(s.start); };
    }
    var byKey = {};
    series.forEach(function(b) { byKey[b.key] = b; });
    inS.forEach(function(s) { var b = byKey[keyFn(s)]; if (b) { b.visits++; b.vset[s.vid] = 1; } });
    series = series.map(function(b) { return { key: b.key, label: b.label, visits: b.visits, visitors: Object.keys(b.vset).length }; });

    // Busiest hours (visitor's browser time shown in the admin's time zone)
    var hours = []; for (var hh = 0; hh < 24; hh++) hours.push(0);
    inS.forEach(function(s) { hours[new Date(s.start).getHours()]++; });

    // Event breakdowns
    var pages = {}, projects = {}, contacts = {};
    var act = { cv: 0, contact: 0, cta: 0, form: 0, certs: 0, photos: 0, demos: 0, recs: 0, projectViews: 0 };
    inE.forEach(function(e) {
      if (e.type === 'page_view') tally(pages, e.page || 'intro');
      else if (e.type === 'project_view') { act.projectViews++; tally(projects, (e.detail || '').replace(/^Explored project:\s*/i, '') || 'Project'); }
      else if (e.type === 'cv_download' || e.type === 'cv_click') act.cv++;
      else if (e.type === 'contact_click') { act.contact++; tally(contacts, (e.detail || '').replace(/^Clicked contact:\s*/i, '') || 'Contact'); }
      else if (e.type === 'cta_click') { act.cta++; tally(contacts, e.detail || 'Call to action'); }
      else if (e.type === 'contact_form') act.form++;
      else if (e.type === 'cert_view') act.certs++;
      else if (e.type === 'photo_view') act.photos++;
      else if (e.type === 'dashboard_open') act.demos++;
      else if (e.type === 'recommendation_view') act.recs++;
    });

    // Audience breakdowns (by visit)
    var devices = {}, browsers = {}, os = {}, sources = {}, countries = {}, langs = {}, screens = {};
    inS.forEach(function(s) {
      tally(devices, s.device || 'Desktop'); tally(browsers, s.browser || 'Other'); tally(os, s.os || 'Other');
      tally(sources, sourceOf(s.ref)); tally(countries, countryOf(s.tz));
      if (s.lang) tally(langs, s.lang.toLowerCase());
      if (s.screen && s.screen !== 'Unknown') tally(screens, s.screen);
    });

    // Live feed (newest first; background timing events are hidden)
    var feed = evs.filter(function(e) { return e.type !== 'time_on_site'; }).slice(-150).reverse();

    var fiveMin = {};
    evs.forEach(function(e) { if (now - e.time < 5 * 60000) fiveMin[e.vid] = 1; });

    var allV = {}; sessions.forEach(function(s) { allV[s.vid] = 1; });

    return {
      days: days, kpis: cur, prev: prev, series: series, hours: hours,
      pages: toList(pages), projects: toList(projects, 8), contacts: toList(contacts, 6), actions: act,
      devices: toList(devices), browsers: toList(browsers), os: toList(os), sources: toList(sources, 8),
      countries: toList(countries, 8), languages: toList(langs, 6), screens: toList(screens, 6),
      feed: feed, online: Object.keys(fiveMin).length,
      today: kpis(sessions, evs, todayStart, end, firstSeen),
      allTime: { visits: sessions.length, visitors: Object.keys(allV).length, events: evs.length },
      firstEvent: evs.length ? evs[0].time : 0, lastEvent: evs.length ? evs[evs.length - 1].time : 0,
      hasData: evs.length > 0
    };
  }

