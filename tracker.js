  var BASE_COLS = 'id,visitor_id,event_type,detail,page,device,browser,os,screen,referrer,timezone,created_at';
  var FULL_COLS = BASE_COLS + ',session_id,language';

  function fetchAll(c, token, cols) {
    var out = [], page = 0, PAGE = 1000, MAX = 10;
    function next() {
      return fetch(c.url + '/rest/v1/site_activities?select=' + cols + '&order=created_at.desc&limit=' + PAGE + '&offset=' + (page * PAGE), {
        headers: { 'apikey': c.anon, 'Authorization': 'Bearer ' + token }
      }).then(function(r) {
        if (!r.ok) return r.text().then(function(t) { var e = new Error(t || ('HTTP ' + r.status)); e.status = r.status; e.body = t; throw e; });
        return r.json();
      }).then(function(rows) {
        out = out.concat(rows); page++;
        if (rows.length === PAGE && page < MAX) return next();
        return { rows: out, truncated: rows.length === PAGE && page >= MAX };
      });
    }
    return next();
  }

  function rowToEvent(r) {
    return {
      id: 'sb_' + r.id, time: r.created_at ? Date.parse(r.created_at) : Date.now(), vid: r.visitor_id || 'unknown',
      sid: r.session_id || '', type: r.event_type, detail: r.detail || '', page: r.page || 'intro',
      device: r.device || 'Desktop', browser: r.browser || 'Other', os: r.os || 'Other', screen: r.screen || '',
      referrer: r.referrer || 'Direct', tz: r.timezone || '', lang: r.language || ''
    };
  }

  // Resolves { events, isRemote, configured, error, errorText, truncated }. Never rejects.
  function getEvents(token) {
    var c = cfg();
    var configured = !!(c.url && c.anon);
    var local = function() { return getLocalActivities(); };
    if (configured && token) {
      return fetchAll(c, token, FULL_COLS).catch(function(e) {
        if (e.status === 400) return fetchAll(c, token, BASE_COLS);   // older table without the newer columns
        throw e;
      }).then(function(res) {
        return { events: res.rows.map(rowToEvent), isRemote: true, configured: true, error: null, errorText: '', truncated: res.truncated };
      }).catch(function(e) {
        var body = e && e.body || '';
        var kind = (e && e.status === 404) || /PGRST205|PGRST106|does not exist/i.test(body) ? 'missing_table'
          : (e && (e.status === 401 || e.status === 403)) ? 'denied' : 'error';
        return { events: local(), isRemote: false, configured: true, error: kind, errorText: String(body || (e && e.message) || '').slice(0, 200), truncated: false };
      });
    }
    return Promise.resolve({ events: local(), isRemote: false, configured: configured, error: configured ? 'signed_out' : null, errorText: '', truncated: false });
  }

